def current_locale() -> str:
    return str(st.session_state.get("locale", DEFAULT_LOCALE))


def tr(key: str, *, locale: str | None = None, **params: object) -> str:
    selected = locale or current_locale()
    messages = _MESSAGES.get(selected, _MESSAGES[DEFAULT_LOCALE])
    template = messages.get(key) or _MESSAGES[DEFAULT_LOCALE].get(key) or key
    return template.format(**params)
